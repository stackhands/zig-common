#!/usr/bin/env python3
"""Write src/pytext_nd.zig from Python's unicodedata.

    python3 tools/gen_pytext_nd.py > src/pytext_nd.zig
    python3 tools/gen_pytext_nd.py --check src/pytext_nd.zig

Python's float() and int() read every character with a decimal value as
that digit. unicodedata.decimal is the same property. Each run of decimal
digits in Unicode is ten consecutive code points from the digit zero, so
the table holds the code point of each zero, and the script stops if the
data ever stops being laid out that way. The header names the Python and
Unicode versions the table came from.

The checked-in table pins the Unicode version. --check reads the version
from the file's header and compares the table only under a Python whose
unicodedata is that version, ignoring the header; it fails when the data
has digits the file does not. Under any other Unicode version it compares
nothing and exits with status 3 and a message that names both versions.
"""

import re
import sys
import unicodedata

HEADER = "//! "
OTHER_UNICODE = 3


def pinned_unicode(text):
    """The Unicode version a table's header names, or None."""
    match = re.search(r"^//! Python \S+, Unicode (\S+),", text, re.MULTILINE)
    return match.group(1) if match else None


def zero_starts():
    digits = {}
    for cp in range(0x110000):
        value = unicodedata.decimal(chr(cp), None)
        if value is not None:
            digits[cp] = value
    starts = []
    for cp in sorted(digits):
        if digits[cp] == 0:
            starts.append(cp)
    covered = {}
    for zero in starts:
        for offset in range(10):
            covered[zero + offset] = offset
    if covered != digits:
        raise SystemExit("the decimal digits are not runs of ten from a zero")
    return starts


def render():
    starts = zero_starts()
    lines = [
        "//! The code point of each decimal digit zero in Unicode, from Python's",
        "//! unicodedata. Generated by tools/gen_pytext_nd.py; do not edit.",
        "//!",
        "//! Python %s, Unicode %s, %d runs of ten digits."
        % (sys.version.split()[0], unicodedata.unidata_version, len(starts)),
        "",
        "pub const zeros = [_]u21{",
    ]
    lines.extend("    0x%x," % cp for cp in starts)
    lines.append("};")
    return "\n".join(lines) + "\n"


def body(text):
    return [line for line in text.splitlines() if not line.startswith(HEADER)]


def main(argv):
    if len(argv) == 3 and argv[1] == "--check":
        with open(argv[2], encoding="utf-8") as handle:
            have = handle.read()
        pin = pinned_unicode(have)
        if pin is None:
            sys.stderr.write("%s names no Unicode version in its header\n" % argv[2])
            return 1
        if pin != unicodedata.unidata_version:
            sys.stderr.write(
                "%s is pinned to Unicode %s, and this Python's unicodedata is "
                "Unicode %s; nothing was compared. Run the check with a Python "
                "whose unicodedata is Unicode %s.\n"
                % (argv[2], pin, unicodedata.unidata_version, pin)
            )
            return OTHER_UNICODE
        if body(have) != body(render()):
            sys.stderr.write(
                "%s does not match unicodedata; run tools/gen_pytext_nd.py\n" % argv[2]
            )
            return 1
        return 0
    if len(argv) != 1:
        sys.stderr.write("usage: gen_pytext_nd.py [--check FILE]\n")
        return 2
    sys.stdout.write(render())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
